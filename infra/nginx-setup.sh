#!/bin/sh
# Put nginx (HTTPS + load balancing) in front of the Lociros API replicas.
# Usage: sudo sh infra/nginx-setup.sh api.lociros.com you@example.com
# Point the domain's A record at the instance's static IP first. Safe to re-run:
# it rewrites the config, refreshes the PROXY_SECRET map, and keeps the certificate.
set -eu

DOMAIN="${1:-${API_DOMAIN:-}}"
EMAIL="${2:-${CERTBOT_EMAIL:-}}"
if [ -z "$DOMAIN" ] || [ -z "$EMAIL" ]; then
  echo "Usage: sudo sh infra/nginx-setup.sh api.example.com you@example.com" >&2
  exit 1
fi
if [ "$(id -u)" -ne 0 ]; then
  echo "Run with sudo." >&2
  exit 1
fi
HERE="$(cd "$(dirname "$0")" && pwd)"
ENV_FILE="${ENV_FILE:-/opt/lociros/.env}"
API_REPLICAS="${API_REPLICAS:-2}"
SWAP_SIZE="${SWAP_SIZE:-2G}"

# Each warm replica holds ~1.7 GB of language models. Swap absorbs a spike
# instead of the kernel killing a replica.
if ! swapon --show | grep -q .; then
  echo "Adding $SWAP_SIZE swap..."
  fallocate -l "$SWAP_SIZE" /swapfile
  chmod 600 /swapfile
  mkswap /swapfile
  swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
  sysctl -w vm.swappiness=10
  echo 'vm.swappiness=10' > /etc/sysctl.d/99-lociros.conf
fi

if systemctl is-active --quiet caddy 2>/dev/null; then
  echo "Stopping Caddy (nginx takes over ports 80 and 443)..."
  systemctl disable --now caddy
fi

if ! command -v nginx >/dev/null 2>&1 || ! command -v certbot >/dev/null 2>&1; then
  apt-get update
  apt-get install -y nginx certbot python3-certbot-nginx
fi

# Ubuntu ships 768 connections per worker; each proxied request uses two.
sed -i 's/worker_connections [0-9]*;/worker_connections 4096;/' /etc/nginx/nginx.conf
grep -q '^worker_rlimit_nofile' /etc/nginx/nginx.conf \
  || sed -i '1i worker_rlimit_nofile 16384;' /etc/nginx/nginx.conf

mkdir -p /etc/nginx/lociros

SECRET=""
if [ -f "$ENV_FILE" ]; then
  SECRET="$(sed -n 's/^PROXY_SECRET=//p' "$ENV_FILE" | tail -1 | tr -d '"'"'"' \r')"
fi
if [ -n "$SECRET" ] && ! printf '%s' "$SECRET" | grep -Eq '^[A-Za-z0-9_-]{16,}$'; then
  echo "PROXY_SECRET must be 16+ letters, digits, - or _ (openssl rand -hex 32)." >&2
  exit 1
fi
umask 077
{
  echo "# Generated by infra/nginx-setup.sh from PROXY_SECRET in $ENV_FILE."
  echo 'map $http_x_lociros_proxy $lociros_client {'
  echo '    default $remote_addr;'
  if [ -n "$SECRET" ]; then
    echo "    \"$SECRET\" \$http_x_client_ip;"
  fi
  echo '}'
} > /etc/nginx/lociros/client-key.conf
umask 022
chmod 640 /etc/nginx/lociros/client-key.conf
chown root:www-data /etc/nginx/lociros/client-key.conf
if [ -z "$SECRET" ]; then
  echo "Warning: PROXY_SECRET is not set in $ENV_FILE. Limits will pool visitors behind Vercel's addresses." >&2
fi

if [ ! -f /etc/nginx/lociros/upstream.conf ]; then
  {
    echo "# Rewritten by scripts/lightsail-run.sh on every deploy."
    echo "upstream lociros_api {"
    echo "    least_conn;"
    i=1
    while [ "$i" -le "$API_REPLICAS" ]; do
      echo "    server 127.0.0.1:$((8000 + i)) max_fails=3 fail_timeout=10s;"
      i=$((i + 1))
    done
    echo "    keepalive 64;"
    echo "    keepalive_timeout 60s;"
    echo "}"
  } > /etc/nginx/lociros/upstream.conf
fi

rm -f /etc/nginx/sites-enabled/default
sed "s/__DOMAIN__/$DOMAIN/g" "$HERE/nginx/lociros.conf" > /etc/nginx/conf.d/lociros.conf

nginx -t
systemctl enable nginx
systemctl reload nginx 2>/dev/null || systemctl restart nginx

# certbot adds the 443 server and redirect to the file we just wrote (reusing
# an existing certificate); the certbot systemd timer renews and reloads nginx.
certbot --nginx -d "$DOMAIN" -m "$EMAIL" --agree-tos --non-interactive --redirect --keep-until-expiring
nginx -t
systemctl reload nginx

echo "nginx is serving https://$DOMAIN -> $(grep -c 'server 127' /etc/nginx/lociros/upstream.conf) API replica(s)."
echo "Lightsail firewall: keep 22, 80, 443 open; 8000-8009 stay closed."
echo "Set NLP_BACKEND_URL=https://$DOMAIN on both Vercel projects, PROXY_SECRET on the frontend, and redeploy."
